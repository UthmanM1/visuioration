  ('dataset_process', 30, 3600, 'user', 'Dataset profiling and loading (upload completion, "Prepare for charts"), per user per hour.'),
  ('workspace_create', 5, 3600, 'user', 'Workspaces created with create_workspace(), per user per hour.'),
  ('report_render', 120, 600, 'user', 'Reports rendered with live chart results (viewing, creating or refreshing share links), per user per 10 minutes.'),
  ('report_pdf', 20, 600, 'user', 'Report PDFs generated by signed-in users, per user per 10 minutes.'),
  ('share_pdf_ip', 20, 600, 'public', 'Shared-report PDFs per client IP (salted hash) per 10 minutes.'),
  ('share_pdf_link', 100, 3600, 'public', 'Shared-report PDFs per share link per hour.'),
