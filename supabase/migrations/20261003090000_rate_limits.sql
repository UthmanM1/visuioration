-- Records one hit and reports whether it is within the limit.
create or replace function public.consume_rate_limit(p_bucket text, p_subject text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  pol public.rate_limit_policies;
  v_subject text;
  v_start timestamptz;
  v_hits integer;
begin
  select * into pol from public.rate_limit_policies where bucket = p_bucket;
  if not found then
    raise exception 'Unknown rate limit bucket' using errcode = '22023';
  end if;
  if pol.scope = 'user' then
    if auth.uid() is null then
      raise exception 'Sign in required' using errcode = '42501';
    end if;
    v_subject := auth.uid()::text;
  else
    if p_subject is null or p_subject !~ '^[A-Za-z0-9:_-]{1,128}$' then
      raise exception 'Invalid rate limit subject' using errcode = '22023';
    end if;
    v_subject := p_subject;
  end if;

  v_start := to_timestamp(floor(extract(epoch from now()) / pol.window_seconds) * pol.window_seconds);
  insert into public.rate_limit_counters as c (bucket, subject, window_start, hits)
  values (p_bucket, v_subject, v_start, 1)
  on conflict (bucket, subject, window_start) do update set hits = c.hits + 1
  returning c.hits into v_hits;

  return jsonb_build_object(
    'allowed', v_hits <= pol.max_hits,
    'limit', pol.max_hits,
    'remaining', greatest(pol.max_hits - v_hits, 0),
    'retry_after', case when v_hits <= pol.max_hits then 0
      else greatest(1, ceil(extract(epoch from (v_start + make_interval(secs => pol.window_seconds) - now())))::int) end
  );
end;
$$;

-- For use inside other database functions and triggers: raises PT429 when over the limit.
create or replace function public.enforce_rate_limit(p_bucket text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  r jsonb;
begin
  r := public.consume_rate_limit(p_bucket);
  if not (r ->> 'allowed')::boolean then
    raise exception 'Too many requests. Try again in % seconds.', r ->> 'retry_after'
      using errcode = 'PT429', hint = r ->> 'retry_after';
  end if;
end;
$$;

-- Workspace creation, whichever way it is called.
create or replace function public.create_workspace(workspace_name text, workspace_description text default '')
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  new_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;
  perform public.enforce_rate_limit('workspace_create');
  insert into public.workspaces (name, description, created_by)
  values (trim(workspace_name), coalesce(workspace_description, ''), auth.uid())
  returning id into new_id;
  insert into public.workspace_members (workspace_id, user_id, role)
  values (new_id, auth.uid(), 'owner');
  return new_id;
end;
$$;

-- Dataset records (upload initialisation), whichever way they are created.
create or replace function public.datasets_rate_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null then
    perform public.enforce_rate_limit('dataset_upload_start');
  end if;
  return new;
end;
$$;
create trigger datasets_rate_limit before insert on public.datasets for each row execute function public.datasets_rate_limit();

-- Old windows are removed by the scheduled maintenance job.
create or replace function public.rate_limit_gc()
returns integer
language sql
security definer
set search_path = public
as $$
  with deleted as (
    delete from public.rate_limit_counters c
    using public.rate_limit_policies p
    where p.bucket = c.bucket and c.window_start < now() - make_interval(secs => p.window_seconds * 2)
    returning 1
  )
  select count(*)::integer from deleted;
$$;

revoke execute on function public.consume_rate_limit(text, text) from public;
grant execute on function public.consume_rate_limit(text, text) to anon, authenticated;
revoke execute on function public.enforce_rate_limit(text) from public, anon, authenticated;
revoke execute on function public.datasets_rate_limit() from public, anon, authenticated;
revoke execute on function public.rate_limit_gc() from public, anon, authenticated;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant execute on function public.rate_limit_gc() to service_role';
  end if;
end;
$$;
