-- Application rate limiting, stored in Postgres so every server instance shares the same counters.
--
-- Fixed-window counters: one row per (bucket, subject, window). Each call is a single atomic upsert.
-- Limits are data (rate_limit_policies) and can be tuned without a deploy.
--
--   user buckets    subject is always auth.uid(), taken from the verified JWT; callers can't choose it.
--   public buckets  subject is supplied by the server (a salted hash of the client IP, or of a share token).
--
-- Exceeding a limit raises SQLSTATE PT429, which PostgREST returns as HTTP 429.

create table public.rate_limit_policies (
  bucket text primary key check (bucket ~ '^[a-z_]{1,40}$'),
  max_hits integer not null check (max_hits > 0),
  window_seconds integer not null check (window_seconds between 1 and 86400),
  scope text not null check (scope in ('user', 'public')),
  description text not null default ''
);

create table public.rate_limit_counters (
  bucket text not null references public.rate_limit_policies (bucket) on delete cascade,
  subject text not null check (char_length(subject) between 1 and 128),
  window_start timestamptz not null,
  hits integer not null default 0,
  primary key (bucket, subject, window_start)
);
create index rate_limit_counters_window_idx on public.rate_limit_counters (window_start);

-- Only the functions below touch these tables.
alter table public.rate_limit_policies enable row level security;
alter table public.rate_limit_counters enable row level security;
revoke all on public.rate_limit_policies, public.rate_limit_counters from public, anon, authenticated;

insert into public.rate_limit_policies (bucket, max_hits, window_seconds, scope, description) values
